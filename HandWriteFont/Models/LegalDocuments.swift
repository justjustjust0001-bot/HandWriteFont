import Foundation

enum LegalDocumentKind: String, Identifiable, CaseIterable {
    case termsOfUse
    case privacyPolicy
    case subscriptionTerms

    var id: String { rawValue }

    var title: String {
        switch self {
        case .termsOfUse: return "利用規約"
        case .privacyPolicy: return "プライバシーポリシー"
        case .subscriptionTerms: return "サブスクリプションについて"
        }
    }

    var body: String {
        switch self {
        case .termsOfUse:
            return Self.termsOfUseText
        case .privacyPolicy:
            return Self.privacyPolicyText
        case .subscriptionTerms:
            return Self.subscriptionTermsText
        }
    }

